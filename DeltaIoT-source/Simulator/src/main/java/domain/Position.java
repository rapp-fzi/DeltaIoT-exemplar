package domain;

import java.util.random.RandomGenerator;

public class Position {

    private double x;
    private double y;

    public Position(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public static Position random(RandomGenerator randomGenerator, double range) {
        return new Position(randomGenerator.nextDouble() * range, randomGenerator.nextDouble() * range);
    }

    public double getX() {
        return x;
    }

    public void setX(double x) {
        this.x = x;
    }

    public double getY() {
        return y;
    }

    public void setY(double y) {
        this.y = y;
    }

}
